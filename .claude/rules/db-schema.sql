CREATE TABLE releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    deployment_request_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    environment VARCHAR(32) NOT NULL,
    target_id BIGINT NOT NULL,
    image_digest VARCHAR(80) NOT NULL,
    gitops_commit_sha VARCHAR(64),
    image_repository VARCHAR(500),
    revert_commit_sha VARCHAR(64),
    deadline_at TIMESTAMP WITH TIME ZONE,
    argo_sync_status VARCHAR(32),
    argo_health_status VARCHAR(32),
    previous_good_release_id BIGINT,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_releases PRIMARY KEY (id),
    CONSTRAINT fk_releases_deployment_request_id_deployment_requests FOREIGN KEY(deployment_request_id) REFERENCES deployment_requests (id),
    CONSTRAINT fk_releases_service_id_services FOREIGN KEY(service_id) REFERENCES services (id),
    CONSTRAINT ck_releases_environment CHECK (environment IN ('prod')),
    CONSTRAINT fk_releases_target_id_targets FOREIGN KEY(target_id) REFERENCES targets (id),
    CONSTRAINT fk_releases_previous_good_release_id_releases FOREIGN KEY(previous_good_release_id) REFERENCES releases (id),
    CONSTRAINT ck_releases_release_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'ROLLED_BACK'))
);

CREATE INDEX ix_releases_deployment_request_id ON releases (deployment_request_id);

CREATE INDEX ix_releases_last_known_good ON releases (service_id, environment, target_id, status);
