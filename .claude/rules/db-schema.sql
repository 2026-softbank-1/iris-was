CREATE TABLE github_installations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    installation_id BIGINT NOT NULL,
    account_login VARCHAR(255) NOT NULL,
    account_type VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_github_installations PRIMARY KEY (id),
    CONSTRAINT uq_github_installations_installation_id UNIQUE (installation_id)
);

CREATE TABLE targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(64) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    region VARCHAR(32),
    domain_suffix VARCHAR(255),
    cluster_ref VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_targets PRIMARY KEY (id),
    CONSTRAINT uq_targets_name UNIQUE (name),
    CONSTRAINT ck_targets_target_kind CHECK (kind IN ('AWS', 'LOCAL'))
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    github_id BIGINT NOT NULL,
    login VARCHAR(255) NOT NULL,
    avatar_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_github_id UNIQUE (github_id)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    owner_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    is_deleted BOOLEAN DEFAULT false NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT fk_projects_owner_id_users FOREIGN KEY(owner_id) REFERENCES users (id)
);

CREATE INDEX ix_projects_owner_id ON projects (owner_id);

CREATE UNIQUE INDEX uq_projects_owner_id_name ON projects (owner_id, name) WHERE NOT is_deleted;

CREATE TABLE user_github_installations (
    user_id BIGINT NOT NULL,
    github_installation_id BIGINT NOT NULL,
    CONSTRAINT pk_user_github_installations PRIMARY KEY (user_id, github_installation_id),
    CONSTRAINT fk_user_github_installations_user_id_users FOREIGN KEY(user_id) REFERENCES users (id),
    CONSTRAINT fk_user_github_installations_github_installation_id_git_2fda FOREIGN KEY(github_installation_id) REFERENCES github_installations (id)
);

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    source_repository_url VARCHAR(500) NOT NULL,
    github_installation_id BIGINT NOT NULL,
    source_branch VARCHAR(255) NOT NULL,
    root_directory VARCHAR(255),
    is_auto_deploy BOOLEAN DEFAULT true NOT NULL,
    builder VARCHAR(32),
    dockerfile_path VARCHAR(255),
    platform VARCHAR(32) DEFAULT 'linux/amd64' NOT NULL,
    railpack_version VARCHAR(32),
    analysis_plan JSONB,
    port INTEGER,
    build_command TEXT,
    start_command TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    is_deleted BOOLEAN DEFAULT false NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_services PRIMARY KEY (id),
    CONSTRAINT fk_services_project_id_projects FOREIGN KEY(project_id) REFERENCES projects (id),
    CONSTRAINT fk_services_github_installation_id_github_installations FOREIGN KEY(github_installation_id) REFERENCES github_installations (id),
    CONSTRAINT ck_services_builder CHECK (builder IN ('dockerfile', 'railpack'))
);

CREATE INDEX ix_services_github_installation_id ON services (github_installation_id);

CREATE INDEX ix_services_project_id ON services (project_id);

CREATE UNIQUE INDEX uq_services_project_id_name ON services (project_id, name) WHERE NOT is_deleted;

CREATE TABLE deployment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    service_id BIGINT NOT NULL,
    environment VARCHAR(32) NOT NULL,
    source_sha VARCHAR(64) NOT NULL,
    source_commit_message TEXT,
    trigger_type VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    requested_by BIGINT,
    status VARCHAR(32) NOT NULL,
    failure_code VARCHAR(32),
    variables_snapshot JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_deployment_requests PRIMARY KEY (id),
    CONSTRAINT fk_deployment_requests_service_id_services FOREIGN KEY(service_id) REFERENCES services (id),
    CONSTRAINT ck_deployment_requests_environment CHECK (environment IN ('prod')),
    CONSTRAINT ck_deployment_requests_deployment_trigger CHECK (trigger_type IN ('MANUAL', 'PUSH', 'CLI', 'REDEPLOY', 'ROLLBACK')),
    CONSTRAINT uq_deployment_requests_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_deployment_requests_requested_by_users FOREIGN KEY(requested_by) REFERENCES users (id),
    CONSTRAINT ck_deployment_requests_deployment_status CHECK (status IN ('QUEUED', 'BUILDING', 'DEPLOYING', 'SUCCEEDED', 'FAILED', 'ROLLED_BACK', 'MANUAL_INTERVENTION')),
    CONSTRAINT ck_deployment_requests_failure_code CHECK (failure_code IN ('BUILD_CONFIG_REQUIRED', 'BUILD_FAILED', 'DEPLOY_FAILED'))
);

CREATE INDEX ix_deployment_requests_service_id_created_at ON deployment_requests (service_id, created_at);

CREATE UNIQUE INDEX uq_deployment_requests_active ON deployment_requests (service_id, environment) WHERE status IN ('QUEUED', 'BUILDING', 'DEPLOYING');

